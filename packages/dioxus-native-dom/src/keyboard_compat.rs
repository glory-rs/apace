//! Apace uses keyboard-types 0.8 while dioxus-html 0.7 uses keyboard-types 0.7. The modifier
//! bit values are identical between the two versions.

use dioxus_html::{Code, Key, Location, Modifiers};
use keyboard_types::{
    Code as ApaceCode, Key as ApaceKey, Location as ApaceLocation, Modifiers as ApaceModifiers,
    NamedKey,
};

pub(crate) fn convert_modifiers(modifiers: ApaceModifiers) -> Modifiers {
    Modifiers::from_bits_retain(modifiers.bits())
}

pub(crate) fn convert_location(location: ApaceLocation) -> Location {
    match location {
        ApaceLocation::Standard => Location::Standard,
        ApaceLocation::Left => Location::Left,
        ApaceLocation::Right => Location::Right,
        ApaceLocation::Numpad => Location::Numpad,
    }
}

pub(crate) fn convert_key(key: &ApaceKey) -> Key {
    match key {
        ApaceKey::Character(c) => Key::Character(c.clone()),
        ApaceKey::Named(named) => convert_named_key(*named),
    }
}

